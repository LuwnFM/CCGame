// Serialized PostgreSQL queries for src/storage.ts's single-instance bridge.
import { workerData } from 'node:worker_threads';

const port = workerData.port;
const signal = new Int32Array(workerData.signal);
function reply(payload) {
  port.postMessage(payload);
  Atomics.store(signal, 0, 1);
  Atomics.notify(signal, 0);
}

function translateSql(source) {
  let sql = source.trim();
  const pragma = /^PRAGMA\s+table_info\((\w+)\)$/i.exec(sql);
  if (pragma) {
    return "SELECT column_name AS name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='" + pragma[1] + "'";
  }
  sql = sql.replace(/PRAGMA\s+journal_mode\s*=\s*WAL\s*;/gi, '');
  sql = sql.replace(/\bBEGIN\s+IMMEDIATE\b/gi, 'BEGIN');
  sql = sql.replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi,
    'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  // Millisecond epoch fields do not fit PostgreSQL's 32-bit INTEGER.
  sql = sql.replace(/\bINTEGER\b/gi, 'BIGINT');
  const ignore = /^\s*INSERT\s+OR\s+IGNORE\s+INTO\b/i.test(sql);
  if (ignore) sql = sql.replace(/^\s*INSERT\s+OR\s+IGNORE\s+INTO\b/i, 'INSERT INTO');
  if (ignore) sql = sql.replace(/;?\s*$/, ' ON CONFLICT DO NOTHING');
  // PostgreSQL lowercases unquoted aliases; preserve JSON API field names.
  sql = sql.replace(/\bAS\s+(accountId|createdAt|roomCode)\b/g, (_, alias) => 'AS "' + alias + '"');
  let index = 0;
  sql = sql.replace(/\?/g, () => '$' + ++index);
  return sql;
}

try {
  const { default: pg } = await import('pg');
  // PostgreSQL COUNT() and BIGINT timestamps must remain JS numbers.
  pg.types.setTypeParser(20, value => Number(value));
  const client = new pg.Client({
    connectionString: workerData.connectionString,
    connectionTimeoutMillis: 10000,
    query_timeout: 20000,
    application_name: 'firewell-ccg'
  });
  await client.connect();
  port.on('message', async message => {
    try {
      if (message.op === 'close') {
        await client.end();
        reply({ ok: true });
        return;
      }
      let sql = translateSql(message.sql);
      if (message.op === 'run' && /^\s*INSERT\s+INTO\s+feedback\b/i.test(sql)) {
        sql += ' RETURNING id';
      }
      const result = await client.query(sql, message.params ?? []);
      if (message.op === 'all') reply({ rows: result.rows });
      else if (message.op === 'get') reply({ row: result.rows[0] });
      else if (message.op === 'run') reply({
        changes: { changes: result.rowCount ?? 0, lastInsertRowid: result.rows?.[0]?.id ?? 0 }
      });
      else reply({ ok: true });
    } catch (error) {
      const message = error?.code === '23505'
        ? 'UNIQUE constraint failed: ' + error.message
        : (error?.message ?? String(error));
      reply({ error: message });
    }
  });
  reply({ ready: true });
} catch (error) {
  reply({ error: 'PostgreSQL connection failed: ' + (error?.message ?? String(error)) });
}
